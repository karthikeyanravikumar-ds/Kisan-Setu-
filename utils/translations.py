# TRANSLATION HELPER FUNCTION
# ============================================================

def t(key, language=None, default=None, **kwargs):
    """
    Returns translated string for the given key and language.
    If language is omitted, resolves from active st.session_state["language"].
    Falls back safely to English, then to default (if provided) or the key itself.
    Supports dynamic string interpolation (kwargs).
    """
    if language is None:
        language = get_current_language()
    else:
        language = LANGUAGE_MAP.get(language, "English")

    fallback_val = default if default is not None else key
    lang_dict = TRANSLATIONS.get(language, TRANSLATIONS["English"])
    text_template = lang_dict.get(key)

    if text_template is None:
        # Fallback to English, then to default/key
        text_template = TRANSLATIONS["English"].get(key, fallback_val)

    if kwargs:
        try:
            return text_template.format(**kwargs)
        except Exception:
            return text_template

    return text_template
