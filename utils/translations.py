def get_current_language():
    """Returns normalized active session language ('English', 'Marathi', or 'Hindi')."""
    raw_lang = st.session_state.get("language", "English")
    return LANGUAGE_MAP.get(raw_lang, "English")


def set_current_language(lang_name):
    """Sets normalized active session language."""
    normalized = LANGUAGE_MAP.get(lang_name, "English")
    st.session_state["language"] = normalized
    return normalized


